"""Builds the seed SQL from the catalog.

Dates are written as `public.vaani_today() + N`, and free slots are expanded per *weekday*
and joined to the 7 upcoming dates inside Postgres. So the same SQL file is correct on
whatever day it runs: supabase/seed.sql never goes stale, and seed.py simply executes it.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from datetime import date

from backend.catalog.models import DAYS, Catalog
from backend.catalog.schedule import day_key, doctor_times, offset_to_date, restaurant_times

TODAY = "public.vaani_today()"

# Order matters for truncate + insert (FKs).
DYNAMIC_TABLES = ("call_events", "payments", "bookings", "calls")
CATALOG_TABLES = (
    "doctor_slots",
    "doctors",
    "hospitals",
    "restaurant_slots",
    "restaurant_tables",
    "restaurants",
    "speciality_map",
    "areas",
)


# ---------------------------------------------------------------------------
# SQL literal helpers (no parameters, so the whole seed runs as one script)
# ---------------------------------------------------------------------------


def q(value: object) -> str:
    """Render a Python value as a SQL literal."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | float):
        return repr(value)
    if isinstance(value, str):
        return "'" + value.replace("'", "''") + "'"
    raise TypeError(f"no SQL literal for {type(value).__name__} (use arr() or jsonb())")


def arr(values: Iterable[str]) -> str:
    """text[] literal."""
    items = list(values)
    if not items:
        return "'{}'::text[]"
    return "array[" + ", ".join(q(v) for v in items) + "]::text[]"


def jsonb(value: object) -> str:
    return q(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def _insert(table: str, columns: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    body = ",\n".join("  (" + ", ".join(r) + ")" for r in rows)
    return f"insert into public.{table} ({', '.join(columns)}) values\n{body};\n"


def _values(rows: Iterable[Sequence[str]]) -> str:
    return ",\n".join("    (" + ", ".join(r) + ")" for r in rows)


# ---------------------------------------------------------------------------
# Seed SQL
# ---------------------------------------------------------------------------


def build_seed_sql(cat: Catalog) -> str:
    parts: list[str] = [
        "-- GENERATED by scripts/make_seed_sql.py from data/*.json — do not edit by hand.\n"
        "-- Dates are relative to public.vaani_today() (IST), so this file works on any day.\n"
        "-- Wipes and reloads the catalogue AND all bookings/calls (demo database).\n",
        "begin;\n",
        "truncate "
        + ", ".join(f"public.{t}" for t in DYNAMIC_TABLES + CATALOG_TABLES)
        + " restart identity cascade;\n",
    ]

    parts.append(
        _insert(
            "areas",
            [
                "area_id",
                "name_en",
                "name_te",
                "name_hi",
                "aliases",
                "lat",
                "lng",
                "nearby_unsupported_areas",
                "unsupported_area_reply",
                "is_sample_data",
            ],
            (
                [
                    q(a.area_id),
                    q(a.name_en),
                    q(a.name_te),
                    q(a.name_hi),
                    arr(a.aliases),
                    q(a.lat),
                    q(a.lng),
                    arr(a.nearby_unsupported_areas),
                    jsonb(a.unsupported_area_reply.model_dump()),
                    q(a.is_sample_data),
                ]
                for a in cat.areas
            ),
        )
    )

    parts.append(
        _insert(
            "restaurants",
            [
                "restaurant_id",
                "slug",
                "name",
                "name_spoken_te",
                "name_spoken_hi",
                "name_aliases",
                "area_id",
                "address",
                "cuisines",
                "food_type",
                "rating",
                "price_for_two_inr",
                "highlight",
                "popular_dishes",
                "opening_hours",
                "features",
                "booking_rules",
                "slot_length_minutes",
                "faqs",
                "phone",
                "accent_color",
                "is_sample_data",
            ],
            (
                [
                    q(r.restaurant_id),
                    q(r.slug),
                    q(r.name),
                    q(r.name_spoken_te),
                    q(r.name_spoken_hi),
                    arr(r.name_aliases),
                    q(r.area_id),
                    q(r.address),
                    arr(r.cuisines),
                    q(r.food_type),
                    q(r.rating),
                    q(r.price_for_two_inr),
                    q(r.highlight),
                    arr(r.popular_dishes),
                    jsonb(r.opening_hours),
                    jsonb(r.features.model_dump()),
                    jsonb(r.booking_rules.model_dump()),
                    q(r.slot_length_minutes),
                    jsonb([f.model_dump() for f in r.faqs]),
                    q(r.phone),
                    q(r.accent_color),
                    q(r.is_sample_data),
                ]
                for r in cat.restaurants
            ),
        )
    )

    parts.append(
        _insert(
            "restaurant_tables",
            ["restaurant_id", "table_id", "capacity"],
            ([q(r.restaurant_id), q(t.table_id), q(t.capacity)] for r in cat.restaurants for t in r.tables),
        )
    )

    # Free slots: (restaurant, ISO weekday, time) joined to the next 7 dates.
    rest_rows = [
        [q(r.restaurant_id), str(DAYS.index(day) + 1), q(t)]
        for r in cat.restaurants
        for day in DAYS
        for t in restaurant_times(r, day)
    ]
    parts.append(
        "insert into public.restaurant_slots (restaurant_id, date, time)\n"
        "select v.restaurant_id, d.date, v.time::time\n"
        f"  from (values\n{_values(rest_rows)}\n  ) as v(restaurant_id, isodow, time)\n"
        f"  join (select {TODAY} + o as date from generate_series(0, 6) as o) d\n"
        "    on extract(isodow from d.date) = v.isodow;\n"
    )

    # Pre-booked / blocked exceptions (rows that don't match a slot are ignored).
    if cat.restaurant_availability:
        exc = [
            [q(a.restaurant_id), str(a.day_offset), q(a.time), arr(a.booked_table_ids), q(a.blocked)]
            for a in cat.restaurant_availability
        ]
        parts.append(
            "update public.restaurant_slots s\n"
            "   set booked_table_ids = v.booked, blocked = v.blocked\n"
            f"  from (values\n{_values(exc)}\n  ) as v(restaurant_id, day_offset, time, booked, blocked)\n"
            f" where s.restaurant_id = v.restaurant_id and s.date = {TODAY} + v.day_offset"
            " and s.time = v.time::time;\n"
        )

    parts.append(
        _insert(
            "hospitals",
            [
                "hospital_id",
                "slug",
                "name",
                "name_spoken_te",
                "name_spoken_hi",
                "name_aliases",
                "area_id",
                "type",
                "address",
                "rating",
                "highlight",
                "specialities",
                "facilities",
                "opd_hours",
                "languages_spoken",
                "faqs",
                "phone",
                "accent_color",
                "is_sample_data",
            ],
            (
                [
                    q(h.hospital_id),
                    q(h.slug),
                    q(h.name),
                    q(h.name_spoken_te),
                    q(h.name_spoken_hi),
                    arr(h.name_aliases),
                    q(h.area_id),
                    q(h.type),
                    q(h.address),
                    q(h.rating),
                    q(h.highlight),
                    arr(h.specialities),
                    jsonb(h.facilities.model_dump()),
                    jsonb(h.opd_hours),
                    arr(h.languages_spoken),
                    jsonb([f.model_dump() for f in h.faqs]),
                    q(h.phone),
                    q(h.accent_color),
                    q(h.is_sample_data),
                ]
                for h in cat.hospitals
            ),
        )
    )

    def leave(offsets: list[int]) -> str:
        if not offsets:
            return "'{}'::date[]"
        return "array[" + ", ".join(f"{TODAY} + {o}" for o in sorted(set(offsets))) + "]::date[]"

    parts.append(
        _insert(
            "doctors",
            [
                "doctor_id",
                "hospital_id",
                "name",
                "name_spoken_te",
                "name_spoken_hi",
                "gender",
                "speciality",
                "qualification",
                "experience_years",
                "languages",
                "consultation_fee_inr",
                "schedule",
                "slot_length_minutes",
                "on_leave_dates",
                "is_sample_data",
            ],
            (
                [
                    q(d.doctor_id),
                    q(d.hospital_id),
                    q(d.name),
                    q(d.name_spoken_te),
                    q(d.name_spoken_hi),
                    q(d.gender),
                    q(d.speciality),
                    q(d.qualification),
                    q(d.experience_years),
                    arr(d.languages),
                    q(d.consultation_fee_inr),
                    jsonb(d.schedule),
                    q(d.slot_length_minutes),
                    leave(d.on_leave_day_offsets),
                    q(d.is_sample_data),
                ]
                for d in cat.doctors
            ),
        )
    )

    doc_rows = [
        [q(d.doctor_id), str(DAYS.index(day) + 1), q(t)]
        for d in cat.doctors
        for day in DAYS
        for t in doctor_times(d, day)
    ]
    parts.append(
        "insert into public.doctor_slots (doctor_id, date, time)\n"
        "select v.doctor_id, d.date, v.time::time\n"
        f"  from (values\n{_values(doc_rows)}\n  ) as v(doctor_id, isodow, time)\n"
        f"  join (select {TODAY} + o as date from generate_series(0, 6) as o) d\n"
        "    on extract(isodow from d.date) = v.isodow;\n"
    )

    doc_exc = [
        [q(a.doctor_id), str(a.day_offset), q(t), q(status)]
        for a in cat.doctor_availability
        for status, times in (("booked", a.booked_times), ("blocked", a.blocked_times))
        for t in times
    ]
    if doc_exc:
        parts.append(
            "update public.doctor_slots s set status = v.status\n"
            f"  from (values\n{_values(doc_exc)}\n  ) as v(doctor_id, day_offset, time, status)\n"
            f" where s.doctor_id = v.doctor_id and s.date = {TODAY} + v.day_offset"
            " and s.time = v.time::time;\n"
        )

    m = cat.speciality_mapping
    parts.append(
        _insert(
            "speciality_map",
            ["phrase", "lang", "speciality", "is_emergency"],
            [[q(p.phrase), q(p.lang), q(p.speciality), "false"] for p in m.phrases]
            + [[q(e.phrase), q(e.lang), "null", "true"] for e in m.emergency_phrases]
            # Self-harm phrases are urgent too (no booking); the reply text lives in data/.
            + [[q(e.phrase), q(e.lang), "null", "true"] for e in m.self_harm_phrases],
        )
    )

    parts.append("commit;\n")
    return "\n".join(parts)


# ---------------------------------------------------------------------------
# Python-side preview (dry run, skipped-exception report, tests)
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class SeedPreview:
    restaurant_slots: int
    doctor_slots: int
    skipped: list[str]


def preview(cat: Catalog, today: date) -> SeedPreview:
    """What the seed SQL will produce when run on `today` (IST)."""
    rest_slots = 0
    skipped: list[str] = []
    rest = {r.restaurant_id: r for r in cat.restaurants}
    docs = {d.doctor_id: d for d in cat.doctors}
    for off in range(7):
        day = day_key(offset_to_date(today, off))
        rest_slots += sum(len(restaurant_times(r, day)) for r in cat.restaurants)
    doc_slots = sum(len(doctor_times(d, day_key(offset_to_date(today, off)))) for d in cat.doctors for off in range(7))
    for a in cat.restaurant_availability:
        r = rest.get(a.restaurant_id)
        day = day_key(offset_to_date(today, a.day_offset))
        if r is None or a.time not in restaurant_times(r, day):
            skipped.append(f"restaurant {a.restaurant_id} +{a.day_offset} {a.time} ({day}: not a bookable time)")
    for da in cat.doctor_availability:
        doc = docs.get(da.doctor_id)
        day = day_key(offset_to_date(today, da.day_offset))
        valid = set(doctor_times(doc, day)) if doc else set()
        for t in da.booked_times + da.blocked_times:
            if t not in valid:
                skipped.append(f"doctor {da.doctor_id} +{da.day_offset} {t} ({day}: not in schedule)")
    return SeedPreview(rest_slots, doc_slots, skipped)
